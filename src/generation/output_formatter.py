"""Output Contract Validator enforcing strict regulatory invariants on all assistant responses."""

import re
from typing import List, Tuple
import nltk

from src.utils.logger import get_logger

logger = get_logger(__name__)

# Ensure NLTK tokenizers are available
try:
    nltk.data.find("tokenizers/punkt")
except LookupError:
    nltk.download("punkt", quiet=True)

try:
    nltk.data.find("tokenizers/punkt_tab")
except LookupError:
    nltk.download("punkt_tab", quiet=True)


class OutputContractValidator:
    """Validator enforcing the 3 core Output Contract invariants:
    
    1. Sentence limit: Content is at most THREE (3) complete sentences.
    2. Citation invariant: Exactly ONE valid source URL citation.
    3. Freshness footer: Every response ends with 'Last updated from sources: YYYY-MM-DD'.
    """

    MAX_SENTENCES: int = 3
    URL_REGEX = re.compile(r"https?://[^\s\)\]\"']+")
    DATE_FOOTER_REGEX = re.compile(r"(?:\*?Last updated from sources:\s*\d{4}-\d{2}-\d{2}\*?)", re.IGNORECASE)
    SOURCE_LABEL_REGEX = re.compile(r"\*?\*?Source\*?\*?:\s*(?:\[[^\]]*\]\([^\)]*\)|https?://\S+)", re.IGNORECASE)

    MD_LINK_REGEX = re.compile(r"[\[【][^\]】]*[\]】]\([^\)]*\)?")
    FULLWIDTH_BRACKET_REGEX = re.compile(r"【[^】]*】")

    def _split_into_sentences(self, text: str) -> List[str]:
        """Split text into sentences using NLTK with regex fallback."""
        if not text:
            return []
        try:
            return nltk.sent_tokenize(text)
        except Exception:
            # Fallback regex sentence tokenizer
            parts = re.split(r"(?<=[.!?])\s+", text)
            return [p.strip() for p in parts if p.strip()]

    def extract_content_body(self, text: str) -> str:
        """Strip source lines, URL links, and date footers to isolate pure factual content sentences."""
        clean = text.strip()
        # Remove date footer line
        clean = self.DATE_FOOTER_REGEX.sub("", clean)
        # Remove Source label line
        clean = self.SOURCE_LABEL_REGEX.sub("", clean)
        # Remove any inline markdown links like [GrowwPage](...) or [Source Name](...)
        clean = re.sub(r"[\[{\(【]\s*Groww[^\n\]}\)]*[\]}\)](\([^\)]*\))?.*", "", clean, flags=re.I)
        clean = self.MD_LINK_REGEX.sub("", clean)
        # Remove any full-width citation brackets like 【...】
        clean = self.FULLWIDTH_BRACKET_REGEX.sub("", clean)
        # Remove any stray raw URLs that might remain
        clean = self.URL_REGEX.sub("", clean)
        # Clean up any leftover spacing before punctuation
        clean = re.sub(r"\s+([.,;:!?])", r"\1", clean)
        clean = re.sub(r"\s{2,}", " ", clean)
        return clean.strip()

    def count_content_sentences(self, text: str) -> int:
        """Count the number of content sentences excluding citations and date footers."""
        body = self.extract_content_body(text)
        if not body:
            return 0
        sentences = self._split_into_sentences(body)
        return len(sentences)

    def validate_and_fix(
        self,
        raw_text: str,
        canonical_url: str,
        publish_date: str,
    ) -> str:
        """Enforce all invariants on raw LLM output and return certified compliant response.
        
        Args:
            raw_text: Raw output string generated by LLM.
            canonical_url: Grounded canonical Groww URL for the scheme.
            publish_date: Statutory publication date string (YYYY-MM-DD).
            
        Returns:
            Display-ready compliant markdown string meeting all 3 invariants.
        """
        raw = raw_text.strip()
        if not raw:
            raw = "The provided official documents do not contain this information. Please consult groww.in."

        # Step 1: Extract core content sentences and truncate if > MAX_SENTENCES
        body = self.extract_content_body(raw)
        sentences = self._split_into_sentences(body)

        if len(sentences) > self.MAX_SENTENCES:
            logger.info(
                f"Truncating response from {len(sentences)} sentences to {self.MAX_SENTENCES}"
            )
            sentences = sentences[: self.MAX_SENTENCES]

        content_body = " ".join(sentences).strip()

        # Step 2: Enforce exactly 1 canonical citation block (never embedded in content body)
        clean_url = str(canonical_url) if canonical_url else "https://groww.in/mutual-funds"
        citation_block = f"**Source**: [Groww Scheme Page]({clean_url})"

        # Step 3: Enforce statutory date footer
        clean_date = publish_date or "2026-10-25"
        date_footer = f"*Last updated from sources: {clean_date}*"

        # Assemble compliant response: pure content body + canonical citation + date footer
        parts = [content_body, citation_block, date_footer]
        final_response = "\n\n".join(parts).strip()
        return final_response
